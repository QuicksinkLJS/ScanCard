# Masterset: a tick that comes from the collection asks what to do; Undo in the toast.
import sys; sys.path.insert(0, __import__('os').path.dirname(__file__))
from harness import *
prog = lambda page: page.inner_text('#set-body .mprog p.big')
with sync_playwright() as p:
    b, page = open_app(p)
    open_card(page, 'Blue-Eyes White Dragon')
    page.click('#card-body .versions button >> nth=2'); page.wait_for_timeout(200)
    page.click('#card-add'); page.wait_for_timeout(400)
    print('toast:', page.inner_text('#toast'))
    page.go_back(); page.wait_for_timeout(200)
    page.click('nav.tabs button[data-view=collection]')
    page.click('[data-ctab=masters]')
    page.fill('#masters-search', 'original artwork')
    page.wait_for_selector('#masters-results button')
    page.click('#masters-results button >> nth=0')
    page.wait_for_selector('#set-body .mlist'); page.wait_for_timeout(300)
    page.click('[data-f=have]'); page.wait_for_timeout(200)
    print('start', prog(page))
    page.click('#set-body .tick >> nth=0'); page.wait_for_selector('.choose')
    print('choice:', page.inner_text('.choose').replace('\n', ' | '))
    page.screenshot(path='/home/claude/shots/t15_choice.png')
    page.click(".choose button:has-text(\"Don't count\")"); page.wait_for_timeout(200)
    print('after dont-count', prog(page), '| toast:', page.inner_text('#toast'))
    page.click('.toast-act'); page.wait_for_timeout(200)
    print('after undo', prog(page))
    page.click('#set-body .tick >> nth=0'); page.wait_for_selector('.choose')
    page.click('.choose button:has-text("Remove from collection")'); page.wait_for_timeout(200)
    print('after remove', prog(page), '| coll entries', page.evaluate("JSON.parse(localStorage.getItem('cardscan-collection-v1')).length"))
    page.click('.toast-act'); page.wait_for_timeout(200)
    print('after undo', prog(page), '| coll entries', page.evaluate("JSON.parse(localStorage.getItem('cardscan-collection-v1')).length"))
    page.click('#set-body .tick >> nth=0'); page.wait_for_selector('.choose')
    page.click('.choose button:has-text("Cancel")'); page.wait_for_timeout(200)
    print('after cancel', prog(page), 'dialog gone', page.locator('.choose').count() == 0)
    b.close()
