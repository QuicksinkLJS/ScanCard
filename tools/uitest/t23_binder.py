# Masterset binder: 9 pockets per page, owned in colour, long press leaves a card out, share picture.
import sys; sys.path.insert(0, __import__('os').path.dirname(__file__))
from harness import *
prog = lambda page: page.inner_text('#set-body .mprog p.big')
with sync_playwright() as p:
    b, page = open_app(p)
    open_card(page, 'Blue-Eyes White Dragon')
    page.click('#card-body .versions button >> nth=2'); page.wait_for_timeout(200)
    page.click('#card-add'); page.wait_for_timeout(400); page.go_back(); page.wait_for_timeout(200)
    page.click('nav.tabs button[data-view=collection]')
    page.click('[data-ctab=masters]')
    page.fill('#masters-search', 'original artwork')
    page.wait_for_selector('#masters-results button')
    page.click('#masters-results button >> nth=0')
    page.wait_for_selector('#set-body .mlist'); page.wait_for_timeout(300)
    print('start', prog(page))
    page.click('[data-v=binder]'); page.wait_for_timeout(500)
    print('pages', page.locator('.bpage').count(), '| pockets on page 1', page.locator('.bpage >> nth=0').locator('.pocket').count(), '| have', page.locator('.pocket.have').count(), '|', page.inner_text('#bpager'))
    page.locator('.binder').evaluate("el => el.scrollTo({left: el.clientWidth * 2})"); page.wait_for_timeout(400)
    print('after swipe:', page.inner_text('#bpager'))
    page.locator('.binder').evaluate("el => el.scrollTo({left: 0})"); page.wait_for_timeout(300)
    page.screenshot(path='/home/claude/shots/t23_binder.png')
    # long press a pocket
    box = page.locator('.pocket[data-key] >> nth=1').bounding_box()
    page.mouse.move(box['x'] + 20, box['y'] + 20); page.mouse.down(); page.wait_for_timeout(800); page.mouse.up(); page.wait_for_timeout(300)
    print('after long press', prog(page), '| toast:', page.inner_text('#toast'), '| card page open:', page.is_visible('#card-page'))
    page.click('.toast-act'); page.wait_for_timeout(300)
    print('after undo', prog(page))
    page.evaluate("window.__dl = null; document.addEventListener('click', e => { if (e.target.download) window.__dl = e.target.download; }, true)")
    page.click('#set-share'); page.wait_for_timeout(1500)
    print('share:', page.inner_text('#toast'))
    b.close()
